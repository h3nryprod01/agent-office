#!/usr/bin/env node
// Regenerates THIRD_PARTY_NOTICES.md at the repo root from the installed node_modules of
// packages/{daemon,renderer,protocol}: production dependencies only, transitive ones
// included, each with its license text verbatim, plus the CC0 assets the repo ships.
//
//   npm ci --prefix packages/daemon && npm ci --prefix packages/renderer
//   node packages/daemon/tools/third-party-notices.mjs
//
// A dependency that is not installed is an error, never a silent gap.

import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const LICENSE_FILE = /^(licen[sc]e|copying|notice)(\.|$)/i;

function readJson(file) {
  return JSON.parse(readFileSync(file, "utf8"));
}

/** Node resolution: nearest node_modules/<name> walking up from `fromDir`. */
function resolveInstalled(fromDir, name, stopAt) {
  for (let dir = fromDir; ; dir = path.dirname(dir)) {
    const candidate = path.join(dir, "node_modules", name);
    if (existsSync(path.join(candidate, "package.json"))) return candidate;
    if (dir === stopAt || path.dirname(dir) === dir) return null; // never look in ~/node_modules
  }
}

function licenseTextOf(dir) {
  return readdirSync(dir)
    .filter((f) => LICENSE_FILE.test(f))
    .sort()
    .map((f) => readFileSync(path.join(dir, f), "utf8").trim())
    .join("\n\n");
}

/**
 * @param {string} packageDir  a directory holding package.json (+ node_modules)
 * @returns {{name:string, version:string, license:string, homepage:string, licenseText:string}[]}
 *   production dependencies, transitive, sorted by name@version
 */
export function collectProduction(packageDir, { stopAt = path.resolve(packageDir, "..", "..") } = {}) {
  const seen = new Map();
  const visit = (dir, from) => {
    const manifest = readJson(path.join(dir, "package.json"));
    for (const dep of Object.keys(manifest.dependencies ?? {})) {
      const installed = resolveInstalled(dir, dep, stopAt);
      if (!installed) {
        throw new Error(`${dep} (needed by ${manifest.name ?? from}) is not installed; run npm ci in ${packageDir}`);
      }
      const info = readJson(path.join(installed, "package.json"));
      const key = `${info.name}@${info.version}`;
      if (seen.has(key)) continue;
      const license = typeof info.license === "string" ? info.license : (info.license?.type ?? "see license text");
      seen.set(key, {
        name: info.name,
        version: info.version,
        license,
        homepage: info.homepage ?? (typeof info.repository === "string" ? info.repository : info.repository?.url ?? ""),
        licenseText: licenseTextOf(installed),
      });
      visit(installed, info.name);
    }
  };
  visit(packageDir, path.basename(packageDir));
  return [...seen.values()].sort((a, b) => `${a.name}@${a.version}`.localeCompare(`${b.name}@${b.version}`));
}

/**
 * @param {{packages: ReturnType<typeof collectProduction>[], assets: {name:string, license:string, source:string, note?:string, licenseText?:string}[]}} input
 */
export function renderNotices({ packages, assets }) {
  const merged = new Map();
  for (const list of packages) for (const p of list) merged.set(`${p.name}@${p.version}`, p);
  const lines = [
    "# Third-party notices",
    "",
    "Agent Office itself is MIT-licensed (see `LICENSE`). It includes or depends on the",
    "third-party material below. This file is generated by",
    "`packages/daemon/tools/third-party-notices.mjs` from the installed production",
    "dependencies of `packages/daemon`, `packages/renderer` and `packages/protocol`;",
    "development-only tools (vite, vitest, typescript, ...) are not listed because they",
    "are not shipped. Do not edit by hand: regenerate it.",
    "",
    "## Packages",
    "",
    "| Package | Version | License |",
    "|---|---|---|",
    ...[...merged.values()].map((p) => `| ${p.name} | ${p.version} | ${p.license} |`),
    "",
  ];
  for (const [key, p] of merged) {
    lines.push(`### ${key}`, "", `License: ${p.license}${p.homepage ? ` — ${p.homepage}` : ""}`, "");
    lines.push(p.licenseText ? "```text\n" + p.licenseText + "\n```" : "_No license file was shipped with this package; the license is as declared above._", "");
  }
  lines.push("## Assets", "");
  for (const a of assets) {
    lines.push(`### ${a.name}`, "", `License: ${a.license} — ${a.source}`, "");
    if (a.note) lines.push(a.note, "");
    if (a.licenseText) lines.push("```text\n" + a.licenseText + "\n```", "");
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

function main() {
  const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
  const read = (rel) => readFileSync(path.join(repo, rel), "utf8").trim();
  const packages = ["daemon", "renderer", "protocol"].map((n) => collectProduction(path.join(repo, "packages", n)));
  const assets = [
    {
      name: "Kenney — Isometric Miniature Library (Library Pack 2.1)",
      license: "CC0 1.0",
      source: "https://kenney.nl/assets/isometric-miniature-library",
      note: "Kept unmodified in `assets/third_party/kenney/`; a repacked sprite sheet is in `assets/spritesheets/`. Crediting is not required.",
      licenseText: read("assets/third_party/kenney/isometric-miniature-library/License.txt"),
    },
    {
      name: "RobotExpressive.glb (three.js examples, r171)",
      license: "CC0 1.0",
      source: "https://github.com/mrdoob/three.js/tree/r171/examples/models/gltf",
      note: "Original by Tomás Laulhé, modified by Don McCurdy; released under CC0 (https://creativecommons.org/publicdomain/zero/1.0/). Shipped as `packages/renderer/public/models/RobotExpressive.glb`; see `packages/renderer/public/models/CREDITS.md`.",
    },
  ];
  writeFileSync(path.join(repo, "THIRD_PARTY_NOTICES.md"), renderNotices({ packages, assets }));
  console.log("wrote THIRD_PARTY_NOTICES.md");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
